package app.nzyme.core.rest.authentication;

import java.lang.annotation.Retention;
import java.lang.annotation.Target;

import static java.lang.annotation.ElementType.METHOD;
import static java.lang.annotation.ElementType.TYPE;
import static java.lang.annotation.RetentionPolicy.RUNTIME;

/**
 * Marks a resource (class or method) that can only be accessed with an interactive user session, not with an
 * API key. Use this for anything that manages credentials or sessions, so that a leaked API key cannot be used
 * to create new keys, change passwords, or reset MFA.
 */
@Retention(RUNTIME)
@Target({TYPE, METHOD})
public @interface SessionOnly {
}
